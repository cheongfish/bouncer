'use strict';

// Grading for tasks cut from an upstream repository's real commit (benchmarks/upstream/<task>.json).
// The task snapshot is the commit's parent; the commit's own test files are the hidden tests. A
// submission is graded on a fresh snapshot checkout with its patch applied, the hidden test files
// written over it, and the pinned dependencies linked in. Node built-ins only: the verifier container
// mounts benchmarks/ read-only and has no network.

const { spawn } = require('node:child_process');
const { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, statSync, symlinkSync } = require('node:fs');
const path = require('node:path');
const { benchmarkRoot } = require('./lib.cjs');

const maxOutputBytes = 4 * 1024 * 1024;

function loadUpstreamConfig(configFile) {
  const config = JSON.parse(readFileSync(configFile, 'utf8'));
  if (!/^[a-z][a-z0-9-]*-[0-9]{3}$/.test(config.task_id ?? '')) throw new Error('upstream config needs a task_id');
  if (!/^[0-9a-f]{40}$/.test(config.snapshot?.commit ?? '')) throw new Error('upstream config needs snapshot.commit');
  const points = config.criteria.reduce((sum, criterion) => sum + criterion.points, 0);
  if (points !== 100) throw new Error(`criteria points add up to ${points}, not 100`);
  return config;
}

// Generated by build-upstream-task.cjs and ignored by Git: bundle, hidden tests, dependencies, baseline.
function fixturePaths(taskId, root = benchmarkRoot) {
  const dir = path.join(root, 'fixtures', 'upstream', taskId);
  return {
    dir,
    bundle: path.join(root, 'fixtures', 'upstream', `${taskId}.bundle`),
    hidden: path.join(dir, 'hidden'),
    nodeModules: path.join(dir, 'deps', 'node_modules'),
    baseline: path.join(dir, 'baseline.json'),
  };
}

// Hidden tests are stored as `<path>.hidden` so no test runner in this repository discovers them.
const HIDDEN_SUFFIX = '.hidden';

// The upstream versions win: a submission that edited a hidden test file is graded on upstream's file.
function writeHiddenTests(config, paths, workDir) {
  for (const rel of config.hidden_tests) {
    const target = path.join(workDir, rel);
    mkdirSync(path.dirname(target), { recursive: true });
    cpSync(path.join(paths.hidden, `${rel}${HIDDEN_SUFFIX}`), target);
  }
}

function linkDependencies(paths, workDir) {
  if (!existsSync(paths.nodeModules)) throw new Error(`dependencies are not built: ${paths.nodeModules}`);
  symlinkSync(paths.nodeModules, path.join(workDir, 'node_modules'), 'dir');
}

// The graded project's runner must not report into a parent `node --test`.
function childEnv() {
  const env = { ...process.env, CI: '1' };
  delete env.NODE_TEST_CONTEXT;
  return env;
}

function run(argv, cwd, timeoutMs) {
  return new Promise((resolve) => {
    const child = spawn(argv[0], argv.slice(1), { cwd, env: childEnv(), stdio: ['ignore', 'pipe', 'pipe'] });
    let stdout = '';
    let stderr = '';
    const take = (current, chunk) => (current.length < maxOutputBytes ? current + chunk : current);
    child.stdout.on('data', (chunk) => { stdout = take(stdout, chunk); });
    child.stderr.on('data', (chunk) => { stderr = take(stderr, chunk); });
    let timedOut = false;
    const timer = setTimeout(() => { timedOut = true; child.kill('SIGKILL'); }, timeoutMs);
    child.on('error', (error) => { clearTimeout(timer); resolve({ argv, exit_code: null, timed_out: false, stdout, stderr, error: error.message }); });
    child.on('close', (code, signal) => {
      clearTimeout(timer);
      resolve({ argv, exit_code: code, signal, timed_out: timedOut, stdout, stderr, error: null });
    });
  });
}

// Top-level TAP results from `node --test --test-reporter=tap <one file>`: one row per top-level test.
function topLevelCases(tap) {
  const cases = [];
  for (const line of tap.split('\n')) {
    const match = line.match(/^(not ok|ok) \d+ - (.*?)(\s+#\s*(SKIP|TODO)\b.*)?$/);
    if (match) cases.push({ name: match[2], pass: match[1] === 'ok', skipped: Boolean(match[4]) });
  }
  return cases;
}

function nodeTest(file, { skipPattern } = {}) {
  return ['node', '--test', '--test-reporter=tap', ...(skipPattern ? [`--test-skip-pattern=${skipPattern}`] : []), file];
}

async function pool(items, limit, worker) {
  const results = new Array(items.length);
  let next = 0;
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (next < items.length) {
      const index = next++;
      results[index] = await worker(items[index]);
    }
  }));
  return results;
}

function walk(dir, rel = '') {
  return readdirSync(path.join(dir, rel)).flatMap((name) => {
    const child = path.posix.join(rel, name);
    if (name === 'node_modules') return [];
    return statSync(path.join(dir, child)).isDirectory() ? walk(dir, child) : [child];
  });
}

// Test files the regression criterion considers: the config's suffixes under its roots, minus hidden tests.
function regressionFiles(config, workDir) {
  const { roots, suffixes } = config.regression;
  return roots.flatMap((root) => (existsSync(path.join(workDir, root)) ? walk(workDir, root) : []))
    .filter((file) => suffixes.some((suffix) => file.endsWith(suffix)))
    .filter((file) => !config.hidden_tests.includes(file))
    .sort();
}

async function runRegression(config, workDir, files) {
  const { concurrency, timeout_ms: timeoutMs } = config.regression;
  const results = await pool(files, concurrency, (file) => run(nodeTest(file), workDir, timeoutMs));
  return files.map((file, index) => ({ file, pass: results[index].exit_code === 0 && !results[index].timed_out }));
}

// Each criterion returns { id, points, awarded, pass, detail }. `cases` is proportional over the
// file's top-level tests; `file` and `commands` are all-or-nothing; `regression` is proportional
// over the files that passed on the untouched snapshot.
async function gradeCriterion(criterion, config, workDir, baseline, commands) {
  const { id, points } = criterion;
  if (criterion.kind === 'cases' || criterion.kind === 'file') {
    const result = await run(nodeTest(criterion.file, { skipPattern: criterion.skip_pattern }), workDir, criterion.timeout_ms);
    commands.push({ id, ...summarize(result) });
    const cases = topLevelCases(result.stdout).filter((row) => !row.skipped);
    if (criterion.kind === 'file') {
      const pass = result.exit_code === 0 && !result.timed_out && cases.length > 0;
      return { id, points, awarded: pass ? points : 0, pass, detail: { cases: cases.length } };
    }
    const expected = criterion.expected_cases;
    const passed = result.timed_out ? 0 : cases.filter((row) => row.pass).length;
    const awarded = Math.round((points * Math.min(passed, expected)) / expected * 10) / 10;
    return { id, points, awarded, pass: passed === expected && cases.length === expected,
      detail: { passed, expected, failed: cases.filter((row) => !row.pass).map((row) => row.name) } };
  }
  if (criterion.kind === 'commands') {
    let pass = true;
    for (const argv of criterion.commands) {
      const result = await run(argv, workDir, criterion.timeout_ms);
      commands.push({ id, ...summarize(result) });
      if (result.exit_code !== 0 || result.timed_out) { pass = false; break; }
    }
    return { id, points, awarded: pass ? points : 0, pass, detail: {} };
  }
  if (criterion.kind === 'regression') {
    if (!baseline) throw new Error('regression criterion needs a baseline');
    const results = await runRegression(config, workDir, baseline.passing);
    const broken = results.filter((row) => !row.pass).map((row) => row.file);
    const kept = baseline.passing.length - broken.length;
    const awarded = Math.round((points * kept) / baseline.passing.length * 10) / 10;
    return { id, points, awarded, pass: broken.length === 0, detail: { kept, baseline: baseline.passing.length, broken } };
  }
  throw new Error(`unknown criterion kind: ${criterion.kind}`);
}

function summarize(result) {
  const tail = (text) => (text.length > 4000 ? text.slice(-4000) : text);
  return { argv: result.argv, exit_code: result.exit_code, timed_out: result.timed_out,
    stdout_tail: tail(result.stdout), stderr_tail: tail(result.stderr), error: result.error };
}

async function grade(config, workDir, baseline) {
  const commands = [];
  const criteria = [];
  for (const criterion of config.criteria) {
    criteria.push(await gradeCriterion(criterion, config, workDir, baseline, commands));
  }
  const score = Math.round(criteria.reduce((sum, row) => sum + row.awarded, 0) * 10) / 10;
  return { criteria, score, commands };
}

// Which regression files pass on the untouched snapshot, so a submission is only charged for files it broke.
async function computeBaseline(config, workDir) {
  const files = regressionFiles(config, workDir);
  const results = await runRegression(config, workDir, files);
  return {
    task_id: config.task_id,
    snapshot: config.snapshot.commit,
    passing: results.filter((row) => row.pass).map((row) => row.file),
    failing: results.filter((row) => !row.pass).map((row) => row.file),
  };
}

module.exports = {
  HIDDEN_SUFFIX, computeBaseline, fixturePaths, grade, linkDependencies, loadUpstreamConfig, regressionFiles, topLevelCases,
  writeHiddenTests,
};
